"""Dataset facts for the manuscript: Table 'datasets' and LaTeX macros (manuscript/macros/data.tex).

    python scripts/data_facts.py
"""
from __future__ import annotations

import json
from pathlib import Path

import numpy as np
import pandas as pd

from vigil.config import data_root, load_config, repo_path
from vigil.data import weather
from vigil.data.dataset import load


def fmt(v, nd=1):
    return f"{v:.{nd}f}"


def main():
    cfg = load_config("data")
    rep = json.load(open(repo_path("data", "processed", "build_report.json")))
    d = load()
    m = {}
    m["StudyHours"] = rep["hours"]
    for s in ["train", "val", "test"]:
        a, b = d.split[s]
        m[{"train": "TrainHours", "val": "ValHours", "test": "TestHours"}[s]] = b - a
        m[{"train": "AvailTrain", "val": "AvailVal", "test": "AvailTest"}[s]] = fmt(100 * rep[f"{s}_vwc_availability"])
        m[{"train": "OnsetsTrain", "val": "OnsetsVal", "test": "OnsetsTest"}[s]] = rep[f"{s}_event_onsets"]
    m["EventRateTest"] = fmt(100 * rep["test_event_rate"], 2)
    m["TestDays"] = int(np.ceil(m["TestHours"] / 24))
    m["QcRange"] = rep["qc"]["vwc_out_of_range"]
    m["QcSpikes"] = rep["qc"]["vwc_spikes"]
    m["QcNegT"] = rep["qc"]["t_negative"]
    m["CafDuplicates"] = sum(rep["caf_duplicates"].values())
    m["NLoggers"] = d.N
    # readings are reported in steps of 0.001 m3/m3: share of test channel-hours whose reading is unchanged
    # after the round-robin revisit interval (5.25, 10.5 and 21 h at K = 8, 4, 2)
    xr = d.x.numpy() * d.vwc_std + d.vwc_mean
    a_, b_ = d.split["test"]
    xr = xr[a_:b_]
    for h, nm in [(5, "Five"), (10, "Ten"), (21, "TwentyOne")]:
        A, B = xr[h:], xr[:-h]
        ok = np.isfinite(A) & np.isfinite(B)
        m[f"Unchanged{nm}"] = fmt(100 * float((np.abs(A - B)[ok] < 5e-4).mean()), 0)

    # weather: POWER vs SCAN
    root = data_root()
    pw = weather.load_power(root / cfg["paths"]["power_csv"])
    sc = weather.load_scan(root / cfg["paths"]["scan_csv"])
    j = sc.join(pw, lsuffix="_scan", rsuffix="_power", how="inner")
    def corr(v, daily=False):
        a = j[[f"{v}_scan", f"{v}_power"]]
        if daily:
            a = a.resample("D").sum(min_count=20) if v == "prcp_mm" else a.resample("D").mean()
        a = a.dropna()
        return a.corr().iloc[0, 1]
    m["PowerTempR"] = fmt(corr("temp_c"), 2)
    m["PowerSradR"] = fmt(corr("srad_wm2"), 2)
    m["PowerRhR"] = fmt(corr("rh"), 2)
    m["PowerWindR"] = fmt(corr("wind_ms"), 2)
    m["PowerPrcpRhourly"] = fmt(corr("prcp_mm"), 2)
    m["PowerPrcpRdaily"] = fmt(corr("prcp_mm", True), 2)
    dd = j[["prcp_mm_scan", "prcp_mm_power"]].resample("D").sum(min_count=20).dropna()
    ws, wp = dd.prcp_mm_scan > 1, dd.prcp_mm_power > 1
    m["PowerWetHit"] = fmt(100 * (ws & wp).sum() / ws.sum(), 0)
    m["PowerPrcpTotal"] = int(round(dd.prcp_mm_power.sum()))
    m["ScanPrcpTotal"] = int(round(dd.prcp_mm_scan.sum()))
    m["ScanHours"] = int(len(j.dropna(subset=["temp_c_scan"])))
    raw = pd.read_csv(root / cfg["paths"]["scan_csv"], comment="#")
    m["ScanRows"] = len(raw)
    m["PercScanComplete"] = fmt(100 * raw.drop(columns=["Date"]).notna().mean().mean(), 1)

    # Bitbrains
    cap = repo_path("results", "raw", "capacity", "bitbrains_grid.npz")
    files = sorted((root / cfg["paths"]["bitbrains_dir"]).glob("*.csv"))
    n_rows = 0
    for f in files:
        with open(f, "rb") as fh:
            n_rows += sum(1 for _ in fh) - 1
    m["BBvms"] = len(files)
    m["BBrows"] = n_rows
    if cap.exists():
        g = np.load(cap)
        m["BBdays"] = int(round(g["use_pct"].shape[1] * 300 / 86400))
        m["BBmeanCpu"] = fmt(float(np.nanmean(g["use_pct"])), 1)
        m["BBgridVMs"] = int(g["use_pct"].shape[0])
    out = repo_path("manuscript", "macros")
    out.mkdir(parents=True, exist_ok=True)
    lines = [f"\\newcommand{{\\{k}}}{{{v}}}" for k, v in m.items()]
    (out / "data.tex").write_text("% generated by scripts/data_facts.py\n" + "\n".join(lines) + "\n")
    json.dump({k: (v if not isinstance(v, (np.integer,)) else int(v)) for k, v in m.items()},
              open(repo_path("results", "processed", "data_facts.json"), "w"), indent=1, default=str)

    # Table: dataset characteristics
    tab = r"""\begin{table*}[t]
\centering
\scriptsize
\caption{Datasets used in this study and their roles. All are public; none contains images.}
\label{tab:datasets}
\begin{adjustbox}{max width=\textwidth}
\begin{tabular}{>{\raggedright\arraybackslash}p{2.4cm}>{\raggedright\arraybackslash}p{3.2cm}>{\raggedright\arraybackslash}p{3.3cm}>{\raggedright\arraybackslash}p{2.6cm}>{\raggedright\arraybackslash}p{3.6cm}}
\toprule
Dataset & Content & Size used & Resolution / period & Role in this study \\
\midrule
CAF soil sensor network \citep{data_caf,gasch2017wrr} & VWC and soil temperature at 30--150~cm; DEM, ECa, Bt, texture, bulk density, crops & 42 loggers $\times$ 5 depths $\times$ \num{%(hours)d} h (\num{%(chh)d} channel-hours) & hourly; 2011-01-01 -- 2016-06-16 & ground truth, graph nodes, static covariates; exact replay of budgeted polling \\
NASA POWER \citep{data_power} & air temperature, humidity, precipitation, wind, shortwave radiation (MERRA-2, CERES) & \num{%(hours)d} hourly records, 5 variables & hourly (LST); 2011-01-01 -- 2016-06-16 & model covariates for training and testing \\
NRCS SCAN 2198 \citep{data_scan,schaefer2007scan} & on-farm air temperature, humidity, precipitation, radiation, wind; shallow soil moisture & \num{%(scanrows)d} hourly records, 16 variables & hourly; 2013-07-24 -- 2016-01-05 & validation of gridded weather; robustness test with on-farm inputs \\
GWA-T-12 Bitbrains \citep{data_bitbrains,shen2015bitbrains} & CPU, memory, disk and network use of virtual machines & %(vms)d VMs, \num{%(bbrows)d} records & 5 min; %(bbdays)s days in 2013 & co-tenant load: capacity forecasting and edge--cloud case study \\
\bottomrule
\end{tabular}
\end{adjustbox}
\end{table*}
""" % {"hours": m["StudyHours"], "chh": m["StudyHours"] * d.N * d.D, "scanrows": m["ScanRows"],
       "vms": m["BBvms"], "bbrows": m["BBrows"], "bbdays": m.get("BBdays", "29")}
    tdir = repo_path("manuscript", "tables")
    tdir.mkdir(parents=True, exist_ok=True)
    (tdir / "datasets.tex").write_text(tab)
    print(json.dumps(m, indent=1, default=str))


if __name__ == "__main__":
    main()
